ALTER TABLE public.teams ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS teams_authenticated_read ON public.teams;
CREATE POLICY teams_authenticated_read ON public.teams
  FOR SELECT TO authenticated USING (TRUE);
DROP POLICY IF EXISTS teams_admin_insert ON public.teams;
CREATE POLICY teams_admin_insert ON public.teams
  FOR INSERT TO authenticated WITH CHECK (
    EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin' AND p.status = 'ativo')
  );
GRANT SELECT, INSERT ON public.teams TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.teams_id_seq TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_set_profile_location(p_user_id UUID, p_location TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.profiles admin_profile
    WHERE admin_profile.id = auth.uid()
      AND admin_profile.role = 'admin'
      AND admin_profile.status = 'ativo'
  ) THEN
    RAISE EXCEPTION 'Apenas administrador ativo pode alterar a equipe.';
  END IF;

  IF p_location IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.teams t WHERE t.name = p_location AND t.active = TRUE
  ) THEN
    RAISE EXCEPTION 'Equipe inválida ou inativa.';
  END IF;

  UPDATE public.profiles SET location = p_location WHERE id = p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Perfil não encontrado.'; END IF;
  RETURN TRUE;
END;
$$;
REVOKE ALL ON FUNCTION public.admin_set_profile_location(UUID, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_set_profile_location(UUID, TEXT) TO authenticated;

